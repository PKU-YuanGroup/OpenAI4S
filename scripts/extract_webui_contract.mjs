function generateSmokeBlock(names) {
  const indent = "  ";
  const list = names.map((n) => `${indent}  ${JSON.stringify(n)},`).join("\n");
  const typeofMap = names.map((n) => `${indent}    ${n}: typeof ${n},`).join("\n");
  return [
    `  ${SMOKE_BEGIN}`,
    `${indent}// F-01: per-name typeof preamble for the window-export contract.`,
    `${indent}// app.js is a classic script (\`const S\` is not window.S) and workbench CSP`,
    `${indent}// has no unsafe-eval, so names are unrolled as \`typeof ident\`.`,
    `${indent}const CONTRACT_GLOBALS = Object.freeze([`,
    list,
    `${indent}]);`,
    `${indent}if (!CONTRACT_GLOBALS.length) throw new Error("CONTRACT_GLOBALS is empty");`,
    `${indent}const kinds = await page.evaluate(() => ({`,
    typeofMap,
    `${indent}}));`,
    `${indent}for (const name of CONTRACT_GLOBALS) {`,
    `${indent}  if (!Object.prototype.hasOwnProperty.call(kinds, name) || kinds[name] === "undefined") {`,
    `${indent}    throw new Error(\`missing contract global: \${name}\`);`,
    `${indent}  }`,
    `${indent}}`,
    `${indent}for (const name of Object.keys(kinds)) {`,
    `${indent}  if (!CONTRACT_GLOBALS.includes(name)) {`,
    `${indent}    throw new Error(\`typeof map has extra name not in CONTRACT_GLOBALS: \${name}\`);`,
    `${indent}  }`,
    `${indent}}`,
    `  ${SMOKE_END}`,
  ].join("\n");
}

function parseSmokeGlobals(smokeSource) {
  const begin = smokeSource.indexOf(SMOKE_BEGIN);
  const end = smokeSource.indexOf(SMOKE_END);
  if (begin === -1 || end === -1 || end < begin) return null;
  const block = smokeSource.slice(begin, end);
  const names = [];
  const re = /"([A-Za-z_$][\w$]*)"/g;
  let m;
  while ((m = re.exec(block))) {
    // Only names inside the freeze array, not in comments.
    if (m.index < block.indexOf("Object.freeze")) continue;
    if (m.index > block.indexOf("]);")) continue;
    names.push(m[1]);
  }
  return names;
}

function applySmokePreamble(smokeSource, names) {
  const block = generateSmokeBlock(names);
  const begin = smokeSource.indexOf(SMOKE_BEGIN);
  const end = smokeSource.indexOf(SMOKE_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    let from = begin;
    while (from > 0 && smokeSource[from - 1] === " ") from -= 1;
    if (from > 0 && smokeSource[from - 1] === "\n") {
      // keep a single blank line before the block
    }
    let to = end + SMOKE_END.length;
    if (smokeSource[to] === "\r") to += 1;
    if (smokeSource[to] === "\n") to += 1;
    return smokeSource.slice(0, from) + block + "\n" + smokeSource.slice(to);
  }
  const needle = `  await page.locator("#dashboard").waitFor({ state: "visible" });\n`;
  const at = smokeSource.indexOf(needle);
  if (at === -1) {
    throw new Error("cannot find dashboard wait in tests/browser_smoke.mjs to insert CONTRACT_GLOBALS");
  }
  const insertAt = at + needle.length;
  return smokeSource.slice(0, insertAt) + "\n" + block + "\n" + smokeSource.slice(insertAt);
}

