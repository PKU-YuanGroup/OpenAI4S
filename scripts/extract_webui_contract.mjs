function main(argv) {
  const args = new Set(argv);
  if (args.has("--self-test")) {
    const failures = selfTest();
    if (failures.length) {
      for (const failure of failures) console.error(`self-test: ${failure}`);
      process.exit(1);
    }
    console.log("extract_webui_contract self-test passed");
    return;
  }
  const { inv, globals, markdown } = inventoryFromScan();
  if (args.has("--stdout")) {
    process.stdout.write(markdown);
    return;
  }
  if (args.has("--json")) {
    process.stdout.write(JSON.stringify({
      globals,
      s_private: sortedNames(inv.sFields).filter((n) => inv.sFields.get(n).private),
      s_public: sortedNames(inv.sFields).filter((n) => !inv.sFields.get(n).private),
      s_star_occurrences: inv.sStarHits,
      selectors: sortedNames(inv.selectors),
    }, null, 2) + "\n");
    return;
  }
  if (args.has("--check")) {
    const errors = checkOutputs({ globals, markdown });
    if (errors.length) {
      for (const error of errors) console.error(error);
      process.exit(1);
    }
    console.log(
      `webui contract up to date: ${globals.length} globals, ${inv.sFields.size} S fields, ${inv.sStarHits} S._* hits, ${inv.selectors.size} selectors`,
    );
    return;
  }
  const stats = writeOutputs({ inv, globals, markdown });
  console.log(
    `wrote tests/webui-contract.md and CONTRACT_GLOBALS (${stats.globals} globals, ${stats.sFields} S fields, ${stats.sStarHits} S._* hits, ${stats.selectors} selectors)`,
  );
}

main(process.argv.slice(2));
