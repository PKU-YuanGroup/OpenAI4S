function emptyInventory() {
  return {
    files: [],
    globals: new Map(), // name -> { count, files: Set, lines: [{file,line}] }
    sFields: new Map(), // field -> { read, write, nestedWrite, files, paths: Set, private }
    sStarHits: 0,
    selectors: new Map(), // sel -> { count, files: Set }
  };
}

function addGlobal(inv, name, file, line, n) {
  let row = inv.globals.get(name);
  if (!row) {
    row = { count: 0, files: new Set(), lines: [] };
    inv.globals.set(name, row);
  }
  row.count += n;
  row.files.add(file);
  row.lines.push({ file, line });
}

function addSField(inv, hit, file, line) {
  let row = inv.sFields.get(hit.field);
  if (!row) {
    row = {
      read: 0,
      write: 0,
      nestedWrite: 0,
      files: new Set(),
      paths: new Set(),
      private: hit.field.startsWith("_"),
    };
    inv.sFields.set(hit.field, row);
  }
  row.files.add(file);
  if (hit.kind === "write") {
    row.write += 1;
    row.paths.add(hit.path);
  } else if (hit.kind === "nested-write") {
    row.nestedWrite += 1;
    row.paths.add(hit.path);
  } else {
    row.read += 1;
  }
  if (hit.field.startsWith("_")) inv.sStarHits += 1;
  void line;
}

function addSelector(inv, sel, file) {
  let row = inv.selectors.get(sel);
  if (!row) {
    row = { count: 0, files: new Set() };
    inv.selectors.set(sel, row);
  }
  row.count += 1;
  row.files.add(file);
}

function withoutGeneratedBlock(source) {
  const begin = source.indexOf(SMOKE_BEGIN);
  const end = source.indexOf(SMOKE_END);
  if (begin === -1 || end === -1 || end < begin) return source;
  return source.slice(0, begin) + source.slice(end + SMOKE_END.length);
}

function scanFile(filePath, inv) {
  const source = withoutGeneratedBlock(fs.readFileSync(filePath, "utf8"));
  const file = path.basename(filePath);
  inv.files.push(file);

  CALL_RE.lastIndex = 0;
  let m;
  while ((m = CALL_RE.exec(source))) {
    const arg = parseFirstCallArg(source, m.index + m[0].length - 1);
    if (!arg || arg.kind !== "expr") continue;
    const fn = parseEvaluateFunction(arg.text);
    if (!fn) continue;
    const line = lineAt(source, arg.start);
    const idents = collectFreeIdents(fn.body, fn.locals);
    for (const [name, count] of idents) addGlobal(inv, name, file, line, count);
    for (const hit of collectSAccesses(fn.body)) {
      addSField(inv, hit, file, lineAt(source, arg.start + hit.index));
    }
  }

  for (const selHit of collectSelectorsFromSource(source)) {
    addSelector(inv, selHit.selector, file);
  }
}

function scanAll(files) {
  const inv = emptyInventory();
  for (const filePath of files) scanFile(filePath, inv);
  return inv;
}

