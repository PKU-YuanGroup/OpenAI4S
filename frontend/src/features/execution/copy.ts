export function provenanceT(key: keyof typeof COPY.en, ...args: unknown[]): string {
  return COPY[LANG === "zh" ? "zh" : "en"][key].replace(/\{(\d+)\}/g, (_, n: string) => String(args[Number(n)] ?? ""));
}

