    const beginLines = rewritten.split("\n").filter((line) => line.includes(SMOKE_BEGIN));
    note(beginLines.length === 1 && beginLines[0] === `  ${SMOKE_BEGIN}`, "re-applying the preamble does not accumulate indent", JSON.stringify(beginLines));
